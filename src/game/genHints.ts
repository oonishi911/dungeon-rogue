/** 呪文の項目（key）の説明。amount は呪文によって意味が違う */
export function spellHint(spell: SpellId, key: string): string {
  if (key === 'amount') {
    return spell === 'heal'
      ? '1回で回復するHPです。例：200なら、HPが200回復します。'
      : '1ターンに回復するHPです。例：20で、続くターン数が10なら、合わせて200回復します。';
  }
  return BASE[key] ?? '';
}

